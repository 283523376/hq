-- =============================================================
-- 改制单菜单逻辑删除（修正 V3.9.5_57 用 status 无效的问题）
-- 2026-11-10
-- spec: docs/superpowers/specs/2026-11-10-yx-wms-rk001-gaidaoliao-design.md §3.2
--
-- 为什么需要这条：V57 只把 status 置 '0'，但平台菜单接口
-- （SysPermissionMapper.queryByUserWithTenantId）**不按 status 过滤**，只按授权行 + del_flag，
-- 实测 UI 仍能看到「改制单」。本项目既定惯例是逻辑删除（见 V3.9.5_16 线边柜方案 A 移出）。
-- 保留 V57 不动（已 Flyway 记账、checksum 固定），status=0 作为附加标记无害。
--
-- 处置口径：del_flag=1 逻辑删除，代码与历史数据保留、可回滚（回滚段见文末）。
-- 影响行：1910000000000000973（入库管理 → 改制单）+ 按钮点 0974~0977（wms:conversion:*）。
--
-- 幂等：带 del_flag=0 条件的 UPDATE，可重复执行。
-- =============================================================

UPDATE `sys_permission`
   SET `del_flag` = 1, `update_time` = NOW()
 WHERE `del_flag` = 0
   AND `id` IN ('1910000000000000973','1910000000000000974','1910000000000000975',
                '1910000000000000976','1910000000000000977');

-- 同时清掉各角色对这几个权限点的授权行（del_flag=1 后已不可见，留行会污染审计计数，
-- 且 wms-perms-check.py 按 del_flag=0 比对会误报「代码注解无权限点」）
DELETE rp FROM sys_role_permission rp
 WHERE rp.permission_id IN ('1910000000000000973','1910000000000000974','1910000000000000975',
                            '1910000000000000976','1910000000000000977');

