-- ------------------------------------------------ C1-1: operator 收回 客户档案 / 物料分组映射 页面
DELETE FROM sys_role_permission
WHERE role_id = '191000000000009003'
  AND permission_id IN ('1910000000000000981', '1910000000000000986');

-- ------------------------------------------------ C1-2: stocktake / viewer 收回 库存管理目录（唯一子页=库存调拨，无 transfer:list）
DELETE FROM sys_role_permission
WHERE role_id IN ('191000000000009004', '191000000000009005')
  AND permission_id = '1910000000000000401';

-- ------------------------------------------------ I1: wms_admin 删除 2 个孤儿演示页授权（雪花 id 撞 191 前缀）
DELETE FROM sys_role_permission
WHERE role_id = '191000000000009001'
  AND permission_id IN ('1912753560201089025', '1917957565728198657');

