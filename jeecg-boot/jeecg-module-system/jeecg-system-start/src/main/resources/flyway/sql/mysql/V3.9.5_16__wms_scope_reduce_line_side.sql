-- ---------------------------------------------------------------- 1) 菜单与按钮逻辑删除
UPDATE `sys_permission`
   SET `del_flag` = 1, `update_time` = NOW()
 WHERE `del_flag` = 0
   AND `id` IN (
     -- 采购入库（RK-001）
     '1910000000000000102',
     '1910000000000000111','1910000000000000112','1910000000000000113',
     '1910000000000000114','1910000000000000115',
     -- 检验任务
     '1910000000000000103','1910000000000000116',
     -- 供应商管理
     '1910000000000000021',
     '1910000000000000031','1910000000000000032','1910000000000000033',
     -- 订单管理
     '1910000000000000022',
     '1910000000000000041','1910000000000000042','1910000000000000043',
     '1910000000000000044','1910000000000000045','1910000000000000046'
   );

-- ---------------------------------------------------------------- 2) 目录 redirect 修正
-- 原 redirect 指向已收回的采购入库，改为保留子菜单中 sort 最小的「生产工单」，
-- 避免点击「入库管理」目录 404（V3.9.5_7 的教训）。
UPDATE `sys_permission`
   SET `redirect` = '/wms/work-order', `update_time` = NOW()
 WHERE `id` = '1910000000000000101'
   AND `redirect` = '/wms/inbound/receive';

-- ---------------------------------------------------------------- 3) 线边柜库区停用
UPDATE `wms_warehouse`
   SET `status` = '0', `update_time` = NOW()
 WHERE `id` = '2110885981815907200'
   AND `warehouse_type` = '线边柜'
   AND `status` = '1'
   AND `deleted_at` = 0;
